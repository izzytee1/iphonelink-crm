import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium,webkit} from 'playwright';
import {mkdirSync} from 'node:fs';
const host='http://127.0.0.1:4211',server=spawn('npm',['run','dev','--','--host','127.0.0.1','--port','4211','--strictPort'],{stdio:'ignore'});
const wait=t=>new Promise(r=>setTimeout(r,t));
mkdirSync('visual',{recursive:true});
async function run(engine,mobile,theme){
 const browser=await engine.launch(),page=await browser.newPage({viewport:mobile?{width:390,height:844}:{width:1440,height:900},isMobile:mobile,hasTouch:mobile});
 const issues=[];page.on('pageerror',e=>issues.push(e.message));
 const tag=(mobile?'mobile-':'desktop-')+theme;
 const shot=async name=>page.locator('.np-device').screenshot({path:'visual/v11-'+tag+'-'+name+'.jpg',type:'jpeg',quality:70});
 try{
  await page.goto(host,{waitUntil:'networkidle'});
  await page.evaluate(theme=>document.documentElement.setAttribute('data-theme',theme),theme);
  const search=page.getByRole('button',{name:'Search leads',exact:true});
  assert.equal(await search.count(),1,'Compact lead search button');
  await search.click();assert.equal(await page.getByRole('textbox',{name:'Search leads'}).isVisible(),true);
  await page.getByRole('button',{name:'Close lead search'}).click();
  await page.getByRole('button',{name:'Email',exact:true}).first().click();
  await page.getByRole('button',{name:'Search mail',exact:true}).click();
  assert.ok(await page.getByRole('textbox',{name:'Search mail'}).isVisible());
  await page.getByRole('button',{name:'Close mail search'}).click();
  await page.getByRole('button',{name:'Leads',exact:true}).first().click();
  await page.locator('.np-launch').click();
  await page.locator('.np-root').evaluate((el,theme)=>el.setAttribute('data-theme',theme),theme);
  await page.getByRole('button',{name:'Calls',exact:true}).click();
  await page.getByRole('button',{name:'Phone Keypad'}).click();
  const keys=await page.locator('.np-dial-key').first().evaluate(e=>({color:getComputedStyle(e).color,bg:getComputedStyle(e).backgroundImage}));
  assert.notEqual(keys.bg,'none','Premium keypad colored gradient');
  await shot('keypad');
  await page.getByRole('button',{name:'Back to calls'}).click();
  await page.locator('.np-call-main').first().click();
  const contact=page.locator('.np-detail-screen');
  await contact.waitFor();
  const actions=await contact.locator('.np-action-four button').evaluateAll(els=>els.map(e=>({c:getComputedStyle(e).color,b:getComputedStyle(e).backgroundColor})));
  assert.ok(actions.length===3 && actions.every(v=>v.c!=='rgb(255, 255, 255)'||v.b!=='rgb(255, 255, 255)'),'Contact actions must contrast');
  const textContrast=await contact.locator('.np-detail-card').first().evaluate(e=>{
    const elem=e.querySelector('div>span'),foreground=getComputedStyle(elem).color,background=getComputedStyle(e).backgroundColor;
    const parse=c=>(c.match(/[\d.]+/g)||[]).slice(0,3).map(x=>+x/255);
    const light=c=>parse(c).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((n,v,i)=>n+v*[.2126,.7152,.0722][i],0);
    const a=light(foreground),b=light(background);
    return {ratio:(Math.max(a,b)+.05)/(Math.min(a,b)+.05),foreground,background};
  });
  assert.ok(textContrast.ratio>=4.5,'Contact detail text contrast '+JSON.stringify(textContrast));
  await shot('contact');
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Back to Communications'}).click();
  await page.getByRole('button',{name:'Messages',exact:true}).click();
  assert.equal(await page.locator('.np-bottom-search').count(),0,'Search does not waste space');
  await page.getByRole('button',{name:'Search messages',exact:true}).click();
  await page.getByRole('textbox',{name:'Search messages input'}).waitFor();
  await page.getByRole('button',{name:'Close message search'}).click();
  await page.locator('.np-messages .np-list-row').first().click();
  const msg=page.locator('.np-composebar');
  await msg.getByRole('button',{name:'Attach message file'}).waitFor();
  const comp=await msg.evaluate(el=>{const input=el.querySelector('.np-compose-field input').getBoundingClientRect(),send=el.querySelector('.np-send-button').getBoundingClientRect();return {align:Math.abs(input.y+input.height/2-(send.y+send.height/2)),sendWidth:send.width}});
  assert.ok(comp.align<5,'Message field and send button centers aligned');
  const picker=msg.locator('input[type=file]');
  await picker.setInputFiles({name:'terms.txt',mimeType:'text/plain',buffer:Buffer.from('terms')});
  await page.locator('.np-attachment-chips button').first().waitFor();
  await shot('sms-thread');
  await page.locator('.np-attachment-chips button').first().click();
  await page.getByRole('button',{name:'Back to messages'}).click();
  await page.getByRole('button',{name:'WhatsApp chats'}).click();
  assert.equal(await page.locator('.np-wa-search').count(),0,'WhatsApp search collapsed');
  await page.getByRole('button',{name:'Search WhatsApp chats'}).click();
  await page.locator('.np-wa-search').waitFor();
  await page.getByRole('button',{name:'Close WhatsApp search'}).click();
  const colors=await page.locator('.np-wa-chats .np-avatar').evaluateAll(a=>a.map(e=>getComputedStyle(e).backgroundColor));
  assert.ok(colors.length>=3&&new Set(colors).size===1,'All original avatars same color');
  await shot('whatsapp-list');
  await page.locator('.np-wa-list-row').first().click();
  const wa=page.locator('.np-wa-input');
  assert.ok(await wa.getByRole('button',{name:'Save WhatsApp message locally'}).isVisible(),'WhatsApp send always visible');
  await wa.locator('input[type=file]').setInputFiles({name:'intro.txt',mimeType:'text/plain',buffer:Buffer.from('Intro')});
  await page.locator('.np-attachment-chips button').first().waitFor();
  const bounds=await wa.evaluate(el=>{const i=el.querySelector('label input').getBoundingClientRect(),s=el.querySelector('.np-wa-submit').getBoundingClientRect();return Math.abs(i.y+i.height/2-(s.y+s.height/2))});
  assert.ok(bounds<6,'WA input/send vertically aligned');
  await shot('whatsapp-thread');
  await page.getByRole('button',{name:'Back to WhatsApp chats'}).click();
  await page.getByRole('button',{name:'Messages'}).first().click();
  await page.getByRole('button',{name:'Back to All'}).click();
  await page.locator('.np-root-tabs button').filter({hasText:'Email'}).click();
  const mail=page.locator('.np-gmail-embedded');
  await mail.getByRole('button',{name:'Compose mail inline'}).click();
  assert.equal(await mail.getByRole('button',{name:'Show formatting tools'}).count(),1);
  assert.equal(await mail.locator('.gm-format-bar').count(),0,'Hidden formatting tools by default');
  await mail.getByRole('button',{name:'Show formatting tools'}).click();
  await mail.locator('.gm-format-bar').waitFor();
  await mail.getByRole('button',{name:'Hide formatting tools'}).click();
  assert.equal(await mail.locator('.gm-format-bar').count(),0);
  const geom=await mail.locator('.gm-compose').evaluate(el=>{const a=el.getBoundingClientRect(),p=el.closest('.gm-mail-app').getBoundingClientRect();return {height:a.height,available:p.height,bottom:a.bottom<=p.bottom+1,send:el.querySelector('.gm-send')?.getBoundingClientRect().bottom<=p.bottom+1}});
  assert.ok(geom.height>geom.available*.7&&geom.bottom&&geom.send,'Large composer and Send visible');
  await shot('email-compose');
  assert.deepEqual(issues,[]);
  console.log('v11 premium UI PASS',mobile?'mobile':'desktop',theme,engine===webkit?'WebKit':'Chromium');
 }finally{await browser.close()}
}
try{
 for(let i=0;i<80;i++){try{if((await fetch(host)).ok)break}catch{}await wait(180)}
 await run(chromium,false,'light');
 await run(webkit,true,'light');
 await run(webkit,true,'dark');
}finally{server.kill()}
